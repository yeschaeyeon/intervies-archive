// 생기부 PDF 받는 방법 안내 (저장소 없이도 열 수 있음)
import { h, modal } from './util.js';

export function openDownloadGuide() {
  const step = (n, t, d) => h('div', { class: 'card' }, h('b', null, `${n}  ${t}`), h('p', { class: 'sub' }, d));
  modal('생기부 PDF 받는 방법', h('div', { class: 'stack' },
    step('①', '정부24에 로그인', '정부24(gov.kr)에 접속해 본인 인증으로 로그인해요.'),
    step('②', '학교생활기록부 찾기', '검색창에 "학교생활기록부"를 검색해서 본인 열람·발급 메뉴로 들어가요.'),
    step('③', 'PDF로 저장', '열람·발급 화면에서 PDF 파일로 저장해요. 인쇄 화면에서 "PDF로 저장"을 골라도 돼요.'),
    step('④', '학교를 통해 받기', '온라인으로 어렵다면 학교 행정실이나 담임 선생님께 PDF 파일을 요청할 수 있어요.'),
    h('div', { class: 'note' }, h('b', null, '꼭 확인하세요'),
      '글자를 선택할 수 있는 PDF여야 해요. 사진을 찍거나 스캔한 파일은 읽을 수 없어요. 메뉴 이름은 사이트 개편으로 조금 달라질 수 있어요. 3학년 기록은 공개되지 않는 경우가 많으니 비어 있어도 괜찮아요.')));
}
